import { all, getDb, nowIso, one, run } from "./db";
import { generateApplicationPackage, type PackageOutcome } from "./agents";
import { heartbeatRuntimeWorker, startRuntimeWorker, stopRuntimeWorker } from "./runtime-state";
import { nextProviderRetryAt } from "./provider-health";
import { notify } from "./notify";

/**
 * Durable document recovery.
 *
 * A provider failure during document preparation must not discard a qualified
 * vacancy or repeat discovery. This queue resumes only the document stage for
 * the affected job, using the same verified profile/vacancy facts. Successful
 * documents are never regenerated by this worker.
 */

export type RecoveryStatus = "pending" | "processing" | "retry_scheduled" | "completed" | "waiting_intervention" | "failed";

type RecoveryRow = {
  id: string;
  dedupe_key: string;
  run_id: string;
  job_id: string | null;
  application_id: string | null;
  stage: string;
  status: RecoveryStatus;
  attempts: number;
  available_at: string;
  last_error: string | null;
  created_at: string;
  started_at: string | null;
  finished_at: string | null;
};

type GlobalQueue = typeof globalThis & {
  __atwRecoveryQueue?: { started: boolean; running: boolean; timer?: ReturnType<typeof setTimeout> };
};
const q = globalThis as GlobalQueue;

function queueState() {
  q.__atwRecoveryQueue ??= { started: false, running: false };
  return q.__atwRecoveryQueue;
}

function startTimer(delayMs: number): void {
  const state = queueState();
  if (state.timer) return;
  state.timer = setTimeout(() => {
    state.timer = undefined;
    void processRecoveryQueue();
  }, Math.max(1_000, delayMs));
  state.timer.unref?.();
}

export function startRecoveryQueue(): void {
  const state = queueState();
  if (!state.started) {
    state.started = true;
    startRuntimeWorker("document_recovery", "Durable document-prep recovery queue");
    run(
      "UPDATE recruitment_recovery SET status = 'retry_scheduled', available_at = ? WHERE status = 'processing' AND started_at < ?",
      [nowIso(), new Date(Date.now() - 5 * 60_000).toISOString()],
    );
  }
  heartbeatRuntimeWorker("document_recovery");
  startTimer(1_000);
}

export function stopRecoveryQueue(): void {
  const state = queueState();
  if (state.timer) clearTimeout(state.timer);
  state.timer = undefined;
  state.started = false;
  stopRuntimeWorker("document_recovery", "Stopped with the application process");
}

export function enqueueDocumentRecovery(input: {
  runId: string;
  jobId: string;
  applicationId?: string | null;
  error: string;
}): { queued: boolean; id: string } {
  const dedupe = `documents:${input.runId}:${input.jobId}`;
  const existing = one<RecoveryRow>("SELECT * FROM recruitment_recovery WHERE dedupe_key = ?", [dedupe]);
  if (existing) return { queued: false, id: existing.id };
  const id = `rec_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 9)}`;
  const retryAt = nextProviderRetryAt();
  const available = retryAt ? new Date(Math.max(Date.now() + 2_000, Date.parse(retryAt))).toISOString() : new Date(Date.now() + 5_000).toISOString();
  run(
    `INSERT INTO recruitment_recovery
       (id, dedupe_key, run_id, job_id, application_id, stage, status, attempts, available_at, last_error, created_at)
     VALUES (?, ?, ?, ?, ?, 'documents', 'retry_scheduled', 0, ?, ?, ?)`,
    [id, dedupe, input.runId, input.jobId, input.applicationId ?? null, available, input.error.slice(0, 1200), nowIso()],
  );
  run("UPDATE jobs SET document_state = 'awaiting_documents' WHERE id = ?", [input.jobId]);
  if (input.applicationId) {
    run("UPDATE applications SET status = 'awaiting_documents', last_update = ? WHERE id = ?", [nowIso(), input.applicationId]);
  }
  notify({
    kind: "application_intervention",
    dedupeKey: `documents_waiting:${input.runId}:${input.jobId}`,
    subject: "Documents queued for automatic retry",
    body: `A qualified vacancy is preserved as awaiting document preparation. The run did not repeat discovery. Error: ${input.error.slice(0, 400)}`,
  });
  startRecoveryQueue();
  return { queued: true, id };
}

function hasValidatedCv(jobId: string): boolean {
  return Boolean(
    one<{ id: string }>(
      `SELECT id FROM documents
       WHERE job_id = ? AND kind = 'tailored_cv' AND mime = 'application/pdf'
         AND deleted_at IS NULL AND quality_status = 'passed' AND size_bytes > 0
       ORDER BY created_at DESC LIMIT 1`,
      [jobId],
    ),
  );
}

function documentsPassed(jobId: string): boolean {
  const rows = all<{ kind: string; quality_status: string | null }>(
    "SELECT kind, quality_status FROM documents WHERE job_id = ? AND deleted_at IS NULL AND kind IN ('tailored_cv','cover_letter')",
    [jobId],
  );
  const passed = (kind: string) => rows.some((row) => row.kind === kind && ["passed", "warning", "skipped"].includes(row.quality_status ?? ""));
  return passed("tailored_cv") && passed("cover_letter");
}

function ownerId(): string {
  return one<{ id: string }>("SELECT id FROM users ORDER BY CASE role WHEN 'owner' THEN 0 WHEN 'admin' THEN 1 ELSE 2 END, created_at LIMIT 1")?.id ?? "";
}

type ValidatedRecoveryPackage = { applicationId: string; cvDocumentId: string; coverDocumentId: string };

/** Do not complete a recovery on a package that is not actually linked and validated. */
function validateRecoveredPackage(pkg: PackageOutcome): ValidatedRecoveryPackage {
  if (!pkg.ok || !pkg.applicationId) {
    throw new Error("Document retry did not produce a linked application package.");
  }
  const app = one<{
    id: string;
    status: string;
    cv_document_id: string | null;
    cover_letter_id: string | null;
  }>("SELECT id, status, cv_document_id, cover_letter_id FROM applications WHERE id = ?", [pkg.applicationId]);
  if (!app) throw new Error("Document retry returned an application that does not exist.");
  if (["submitted", "acknowledged", "interview_invited", "interview_completed", "offer_received"].includes(app.status)) {
    throw new Error("Document retry cannot overwrite an application that has already been submitted.");
  }
  if (!app.cv_document_id || !app.cover_letter_id) {
    throw new Error("Document retry did not link both a CV and a cover letter to the application.");
  }
  if (app.cv_document_id === app.cover_letter_id) {
    throw new Error("The application links the same document as both CV and cover letter.");
  }
  const docs = all<{ id: string; kind: string; quality_status: string | null; size_bytes: number }>(
    "SELECT id, kind, quality_status, size_bytes FROM documents WHERE id IN (?, ?) AND deleted_at IS NULL",
    [app.cv_document_id, app.cover_letter_id],
  );
  const cv = docs.find((doc) => doc.id === app.cv_document_id && doc.kind === "tailored_cv");
  const cover = docs.find((doc) => doc.id === app.cover_letter_id && doc.kind === "cover_letter");
  if (!cv || !cover) throw new Error("The linked CV or cover-letter record is missing.");
  if (!["passed", "warning"].includes(cv.quality_status ?? "") || !["passed", "warning"].includes(cover.quality_status ?? "")) {
    throw new Error("The linked CV or cover letter has not passed its document-quality gate.");
  }
  if (Number(cv.size_bytes) <= 0 || Number(cover.size_bytes) <= 0) {
    throw new Error("The linked CV or cover letter has no rendered file.");
  }
  return { applicationId: app.id, cvDocumentId: cv.id, coverDocumentId: cover.id };
}

function completeRecovery(row: RecoveryRow, validated: ValidatedRecoveryPackage): void {
  const at = nowIso();
  run(
    "UPDATE recruitment_recovery SET status = 'completed', application_id = ?, finished_at = ?, available_at = ?, last_error = NULL WHERE id = ?",
    [validated.applicationId, at, at, row.id],
  );
  if (row.job_id) {
    run("UPDATE jobs SET document_state = 'prepared', status = CASE WHEN status = 'rejected' THEN status ELSE 'documents' END WHERE id = ?", [row.job_id]);
    run(
      "UPDATE documents SET status = 'ready', run_id = ? WHERE id IN (?, ?) AND deleted_at IS NULL AND quality_status IN ('passed','warning')",
      [row.run_id, validated.cvDocumentId, validated.coverDocumentId],
    );
  }
  run("UPDATE applications SET run_id = ?, status = 'quality_check', last_update = ? WHERE id = ?", [row.run_id, at, validated.applicationId]);
  run("UPDATE recruitment_runs SET packages_prepared = packages_prepared + 1 WHERE id = ?", [row.run_id]);
  const job = row.job_id
    ? one<{ title: string; company: string }>("SELECT title, company FROM jobs WHERE id = ?", [row.job_id])
    : null;
  const previousFailure = row.last_error ? ` Previous failure retained in task history: ${row.last_error.slice(0, 300)}` : "";
  run(
    `INSERT INTO recruitment_run_agents
       (run_id, agent_key, assignment, status, attempt, output, coordinator_decision, execution_mode, provider, model, started_at, finished_at, created_at)
     VALUES (?, 'cover', ?, 'completed', ?, ?, 'Recovered only the failed document stage; the validated CV was reused and nothing was submitted.', 'deterministic', NULL, NULL, ?, ?, ?)`,
    [
      row.run_id,
      `Recover cover letter for ${job?.title ?? "vacancy"}${job?.company ? ` at ${job.company}` : ""}`,
      row.attempts + 1,
      `Cover letter recovered and linked to application ${validated.applicationId}. Readiness still requires the normal ATS/submission checks.${previousFailure}`,
      row.started_at ?? at,
      at,
      at,
    ],
  );
  notify({
    kind: "documents_ready",
    dedupeKey: `documents_ready:${row.run_id}:${row.job_id}`,
    subject: job ? `Documents ready: ${job.title} at ${job.company}` : "Application documents prepared",
    body: "The preserved vacancy resumed at the document checkpoint. It now waits for the normal ATS/submission checks; nothing was submitted.",
    email: false,
  });
}

/**
 * Process due document recoveries. `prepare` is injectable for controlled tests;
 * production uses the real document generator.
 */
export async function processRecoveryQueue(options: {
  prepare?: (jobId: string, workflowId: string | null, resumeStage?: "cover_only") => Promise<PackageOutcome>;
  now?: Date;
  limit?: number;
} = {}): Promise<{ attempted: number; completed: number; retryScheduled: number; waitingIntervention: number }> {
  const state = queueState();
  if (state.running) return { attempted: 0, completed: 0, retryScheduled: 0, waitingIntervention: 0 };
  state.running = true;
  heartbeatRuntimeWorker("document_recovery");
  const now = options.now ?? new Date();
  const prepare =
    options.prepare ??
    (async (jobId: string, workflowId: string | null, resumeStage?: "cover_only") =>
      generateApplicationPackage(ownerId(), jobId, { workflowId: workflowId ?? undefined, resumeStage }));
  let attempted = 0;
  let completed = 0;
  let retryScheduled = 0;
  let waitingIntervention = 0;
  try {
    // A worker can die after claiming a row but before finishing its package.
    // Requeue only a genuinely stale claim; a live worker in another process
    // keeps its lease and is never duplicated.
    run(
      `UPDATE recruitment_recovery
       SET status = 'retry_scheduled', available_at = ?,
           last_error = COALESCE(last_error, 'Interrupted by a stale worker lease; requeued.')
       WHERE status = 'processing' AND started_at < ?`,
      [now.toISOString(), new Date(now.getTime() - 5 * 60_000).toISOString()],
    );
    for (let i = 0; i < Math.max(1, Math.min(10, options.limit ?? 5)); i += 1) {
      const row = one<RecoveryRow>(
        "SELECT * FROM recruitment_recovery WHERE status IN ('pending','retry_scheduled') AND available_at <= ? ORDER BY available_at LIMIT 1",
        [now.toISOString()],
      );
      if (!row) break;
      const claimed = getDb()
        .prepare("UPDATE recruitment_recovery SET status = 'processing', attempts = attempts + 1, started_at = ? WHERE id = ? AND status IN ('pending','retry_scheduled')")
        .run(now.toISOString(), row.id);
      if (Number(claimed.changes) !== 1) continue;
      attempted += 1;
      heartbeatRuntimeWorker("document_recovery", "Processing a durable document recovery");
      const attempts = row.attempts + 1;
      const runRow = one<{ workflow_id: string | null; status: string }>("SELECT workflow_id, status FROM recruitment_runs WHERE id = ?", [row.run_id]);
      if (!row.job_id || !runRow) {
        run("UPDATE recruitment_recovery SET status = 'failed', last_error = 'Vacancy or run no longer exists.', finished_at = ? WHERE id = ?", [nowIso(), row.id]);
        continue;
      }
      const app = one<{ id: string }>("SELECT id FROM applications WHERE job_id = ? ORDER BY last_update DESC LIMIT 1", [row.job_id]);
      if (app && documentsPassed(row.job_id) && ["quality_check", "quality_review_required", "ready_to_submit", "human_intervention_required"].includes(
        one<{ status: string }>("SELECT status FROM applications WHERE id = ?", [app.id])?.status ?? "",
      )) {
        completeRecovery(
          row,
          validateRecoveredPackage({ ok: true, message: "Existing validated documents retained.", applicationId: app.id, warnings: [] }),
        );
        completed += 1;
        continue;
      }
      try {
        // Stage-aware recovery: when the CV already passed its gate, retry only
        // the cover-letter stage and its readiness projection. A validated CV is
        // never regenerated merely because a downstream task failed.
        const resumeStage = hasValidatedCv(row.job_id) ? "cover_only" : undefined;
        const pkg = await prepare(row.job_id, runRow.workflow_id, resumeStage);
        if (!pkg.ok) throw new Error(pkg.message);
        completeRecovery(row, validateRecoveredPackage(pkg));
        completed += 1;
      } catch (error) {
        const message = (error instanceof Error ? error.message : "Document retry failed.").slice(0, 1200);
        if (attempts >= 3) {
          run(
            "UPDATE recruitment_recovery SET status = 'waiting_intervention', last_error = ?, finished_at = ? WHERE id = ?",
            [message, nowIso(), row.id],
          );
          if (app) run("UPDATE applications SET status = 'human_intervention_required', last_update = ? WHERE id = ?", [nowIso(), app.id]);
          notify({
            kind: "application_intervention",
            dedupeKey: `documents_intervention:${row.run_id}:${row.job_id}`,
            subject: "Document preparation needs your attention",
            body: `Automatic fallback attempts did not prepare the documents. The qualified vacancy is preserved. Last error: ${message}`,
          });
          waitingIntervention += 1;
        } else {
          const providerRetry = nextProviderRetryAt();
          const backoff = Math.round(Math.min(30 * 60_000, 60_000 * 2 ** (attempts - 1)) * (0.8 + Math.random() * 0.4));
          const available = providerRetry
            ? new Date(Math.max(Date.now() + backoff, Date.parse(providerRetry))).toISOString()
            : new Date(Date.now() + backoff).toISOString();
          run(
            "UPDATE recruitment_recovery SET status = 'retry_scheduled', last_error = ?, available_at = ? WHERE id = ?",
            [message, available, row.id],
          );
          if (app) run("UPDATE applications SET status = 'awaiting_documents', last_update = ? WHERE id = ?", [nowIso(), app.id]);
          retryScheduled += 1;
        }
      }
    }
  } finally {
    state.running = false;
    const next = one<{ at: string | null }>(
      "SELECT MIN(available_at) AS at FROM recruitment_recovery WHERE status IN ('pending','retry_scheduled')",
    );
    if (next?.at) startTimer(Math.min(5 * 60_000, Math.max(1_000, Date.parse(next.at) - Date.now() + 100)));
  }
  return { attempted, completed, retryScheduled, waitingIntervention };
}

export function recoverySnapshot() {
  const counts: Record<string, number> = {};
  for (const row of all<{ status: string; n: number }>("SELECT status, COUNT(*) AS n FROM recruitment_recovery GROUP BY status")) {
    counts[row.status] = Number(row.n);
  }
  return {
    counts,
    pending: Number(counts.pending ?? 0) + Number(counts.retry_scheduled ?? 0) + Number(counts.processing ?? 0),
    waitingIntervention: Number(counts.waiting_intervention ?? 0),
    latest: all<RecoveryRow>("SELECT * FROM recruitment_recovery ORDER BY created_at DESC LIMIT 10"),
    nextRetryAt: one<{ at: string | null }>(
      "SELECT MIN(available_at) AS at FROM recruitment_recovery WHERE status IN ('pending','retry_scheduled')",
    )?.at ?? null,
  };
}
